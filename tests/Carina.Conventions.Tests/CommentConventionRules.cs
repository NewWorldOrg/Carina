using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Carina.Conventions.Tests;

public static class CommentConventionRules
{
    private const string GeneratedHeader = "// <auto-generated";

    private static readonly string[] ToolDirectives = ["// ReSharper ", "// csharpier-ignore", "// @formatter:"];

    public static IReadOnlyList<string> CommentsInCode(string directory)
        => Scanned(directory)
            .SelectMany(file => Comments(file.Source).Select(line => $"{file.Relative}:{line}"))
            .Order(StringComparer.Ordinal)
            .ToArray();

    private static IEnumerable<int> Comments(string source)
        => CSharpSyntaxTree.ParseText(source)
            .GetRoot()
            .DescendantTrivia()
            .Where(IsAComment)
            .Where(trivia => !IsAToolDirective(trivia))
            .Select(trivia => trivia.GetLocation().GetLineSpan().StartLinePosition.Line + 1);

    private static bool IsAComment(SyntaxTrivia trivia)
        => trivia.Kind() is SyntaxKind.SingleLineCommentTrivia
            or SyntaxKind.MultiLineCommentTrivia
            or SyntaxKind.SingleLineDocumentationCommentTrivia
            or SyntaxKind.MultiLineDocumentationCommentTrivia;

    private static bool IsAToolDirective(SyntaxTrivia trivia)
        => trivia.Kind() is SyntaxKind.SingleLineCommentTrivia
           && ToolDirectives.Any(directive => trivia.ToString().StartsWith(directive, StringComparison.Ordinal));

    private static IEnumerable<SourceFile> Scanned(string directory)
        => Directory
            .EnumerateFiles(directory, "*.cs", SearchOption.AllDirectories)
            .Where(file => !IsBuildOutput(file))
            .Select(file => new SourceFile(
                "/" + Path.GetRelativePath(directory, file).Replace('\\', '/'),
                File.ReadAllText(file)))
            .Where(file => !IsGenerated(file.Source));

    private static bool IsBuildOutput(string path)
    {
        string[] segments = path.Split(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);

        return segments.Contains("obj", StringComparer.Ordinal) || segments.Contains("bin", StringComparer.Ordinal);
    }

    private static bool IsGenerated(string source)
        => source.TrimStart('﻿').StartsWith(GeneratedHeader, StringComparison.Ordinal);

    private readonly record struct SourceFile(string Relative, string Source);
}
