namespace Carina.Conventions.Tests;

public sealed class CommentConventionRuleSelfCheckTests
{
    private const string InAFile = "Carina.Infrastructure/Widgets/Widget.cs";

    public static TheoryData<string> EveryKindOfComment =>
    [
        "// said aside\nclass Widget { }",
        "class Widget { int count; // trailing\n}",
        "/// <summary>Said aside.</summary>\nclass Widget { }",
        "/** said aside */\nclass Widget { }",
        "class Widget { /* said inline */ int count; }",
        "/* said\nover lines */\nclass Widget { }",
        "class Widget { void Run() { /* nothing */ } }",
        "#pragma warning disable CS0169\n// said after a directive\nclass Widget { }",
    ];

    public static TheoryData<string> EveryStringLiteralHoldingASlashPair =>
    [
        "class Widget { string said = \"// not a comment\"; }",
        "class Widget { string said = \"/* not a comment */\"; }",
        "class Widget { string said = @\"// not\n// a comment\"; }",
        "class Widget { string said = $\"// {name} not a comment\"; }",
        "class Widget { string said = $@\"// {name} not a comment\"; }",
        "class Widget { string said = \"\"\"\n    // not a comment\n    /// nor this\n    \"\"\"; }",
        "class Widget { string said = $$\"\"\"\n    // {{name}} not a comment\n    \"\"\"; }",
        "class Widget { string said = $\"{name + \"//\"} not a comment\"; }",
        "class Widget { char slash = '/'; string said = \"*/\"; }",
    ];

    public static TheoryData<string> EveryDirectiveAToolReads =>
    [
        "#nullable disable\nclass Widget { }",
        "#pragma warning disable CS0169\nclass Widget { int count; }\n#pragma warning restore CS0169",
        "#if DEBUG\nclass Widget { }\n#endif",
        "#region Widgets\nclass Widget { }\n#endregion",
        "// csharpier-ignore\nclass Widget { }",
        "// ReSharper disable once UnusedMember.Global\nclass Widget { }",
        "// @formatter:off\nclass Widget { }\n// @formatter:on",
    ];

    public static TheoryData<string> EveryWayAGeneratedFileOpens =>
    [
        "// <auto-generated />\n// said aside\nclass Widget { }",
        "﻿// <auto-generated />\n/// <inheritdoc />\nclass Widget { }",
        "// <auto-generated>\n//     said by a tool\n// </auto-generated>\nclass Widget { }",
    ];

    [Theory]
    [MemberData(nameof(EveryKindOfComment))]
    public void DetectsThisKindOfComment(string source)
    {
        using SourceTree tree = new();
        tree.Write(InAFile, source);

        Assert.NotEmpty(CommentConventionRules.CommentsInCode(tree.Root));
    }

    [Theory]
    [MemberData(nameof(EveryStringLiteralHoldingASlashPair))]
    public void IgnoresASlashPairInThisKindOfStringLiteral(string source)
    {
        using SourceTree tree = new();
        tree.Write(InAFile, source);

        Assert.Empty(CommentConventionRules.CommentsInCode(tree.Root));
    }

    [Theory]
    [MemberData(nameof(EveryDirectiveAToolReads))]
    public void LetsThisDirectiveThrough(string source)
    {
        using SourceTree tree = new();
        tree.Write(InAFile, source);

        Assert.Empty(CommentConventionRules.CommentsInCode(tree.Root));
    }

    [Theory]
    [MemberData(nameof(EveryWayAGeneratedFileOpens))]
    public void LeavesAGeneratedFileAlone(string source)
    {
        using SourceTree tree = new();
        tree.Write(InAFile, source);

        Assert.Empty(CommentConventionRules.CommentsInCode(tree.Root));
    }

    [Fact]
    public void LeavesBuildOutputAlone()
    {
        using SourceTree tree = new();
        tree.Write("Carina.Infrastructure/obj/Widget.cs", "// said aside\nclass Widget { }");
        tree.Write("Carina.Infrastructure/bin/Widget.cs", "// said aside\nclass Widget { }");

        Assert.Empty(CommentConventionRules.CommentsInCode(tree.Root));
    }

    [Fact]
    public void NamesTheFileAndTheLineOfEachComment()
    {
        using SourceTree tree = new();
        tree.Write(InAFile, "class Widget\n{\n    int count; // trailing\n\n    /// <summary>Said.</summary>\n    int other;\n}");

        Assert.Equal([$"/{InAFile}:3", $"/{InAFile}:5"], CommentConventionRules.CommentsInCode(tree.Root));
    }

    private sealed class SourceTree : IDisposable
    {
        private readonly DirectoryInfo directory = Directory.CreateTempSubdirectory("carina-comment-convention-rules-");

        public string Root => directory.FullName;

        public void Write(string path, string source)
        {
            string full = Path.Combine(Root, path.Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(full)!);
            File.WriteAllText(full, source);
        }

        public void Dispose() => directory.Delete(recursive: true);
    }
}
